// Picks the murderer at random, writes src/phase2.js and the encrypted solution.
// The choice is never printed or stored in plain text.
//   node scripts/new-case.js                       (real run, uses .sealed/reviewer-passphrase.txt)
//   node scripts/new-case.js --force <id>          (testing only: choose a specific candidate)
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { CANDIDATES, buildPhase2, solutionFor } = require('../src/case.js');

const forceIdx = process.argv.indexOf('--force');
const X = forceIdx > 0 ? process.argv[forceIdx + 1] : CANDIDATES[crypto.randomInt(CANDIDATES.length)];
const root = path.join(__dirname, '..');
const data = buildPhase2(X);
fs.writeFileSync(path.join(root, 'src', 'phase2.js'), '// Generated by scripts/new-case.js from src/phase2.base.js. Do not edit by hand.\nmodule.exports = ' + JSON.stringify(data, null, 1) + ';\n');

const pass = fs.readFileSync(path.join(root, '.sealed', 'reviewer-passphrase.txt'), 'utf8').trim();
const salt = crypto.randomBytes(16), iv = crypto.randomBytes(12), iter = 310000;
const c = crypto.createCipheriv('aes-256-gcm', crypto.pbkdf2Sync(pass, salt, iter, 32, 'sha256'), iv);
const ct = Buffer.concat([c.update(solutionFor(X), 'utf8'), c.final(), c.getAuthTag()]);
fs.writeFileSync(path.join(root, 'src', 'solution.enc.json'), JSON.stringify({ v: 1, iter, salt: salt.toString('base64'), iv: iv.toString('base64'), ct: ct.toString('base64') }));
console.log('case generated and sealed');
